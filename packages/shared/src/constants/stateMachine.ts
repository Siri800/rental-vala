export const BOOKING_TRANSITIONS: Record<string, string[]> = {
  DRAFT: ['PENDING_PROVIDER_APPROVAL', 'PAYMENT_PENDING', 'CANCELLED'],
  PENDING_PROVIDER_APPROVAL: ['APPROVED', 'PAYMENT_PENDING', 'CANCELLED'],
  APPROVED: ['PAYMENT_PENDING', 'CANCELLED'],
  PAYMENT_PENDING: ['CONFIRMED', 'CANCELLED'],
  CONFIRMED: ['READY_FOR_PICKUP', 'OUT_FOR_DELIVERY', 'CANCELLED', 'REFUND_PENDING'],
  READY_FOR_PICKUP: ['ACTIVE', 'CANCELLED', 'DISPUTED'],
  OUT_FOR_DELIVERY: ['ACTIVE', 'DISPUTED'],
  ACTIVE: ['RETURN_REQUESTED', 'RETURNED', 'DISPUTED'],
  RETURN_REQUESTED: ['RETURNED', 'DISPUTED'],
  RETURNED: ['INSPECTION_PENDING', 'DISPUTED'],
  INSPECTION_PENDING: ['COMPLETED', 'DISPUTED'],
  COMPLETED: ['DISPUTED'],
  CANCELLED: ['REFUND_PENDING'],
  REFUND_PENDING: ['REFUNDED'],
  REFUNDED: [],
  DISPUTED: ['COMPLETED', 'REFUND_PENDING', 'REFUNDED'],
};

export function canTransitionBooking(fromStatus: string, toStatus: string): boolean {
  const allowed = BOOKING_TRANSITIONS[fromStatus] || [];
  return allowed.includes(toStatus);
}

